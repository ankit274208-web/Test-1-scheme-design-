SELECT UPPER(CONCAT(FIRSTNAME, ' ', LASTNAME))AS FULL_NAME FROM COURSEENROLLMENTS;

 SELECT CONCAT(UPPER(LEFT(FIRSTNAME,1)),SUBSTRING(FIRSTNAME,2)) AS FORMATEDNAME FROM COURSEENROLLMENTS;
 
 SELECT CONCAT(UPPER(LEFT(COURSENAME,3)), '-', STUDENTID) AS STUDENTCODE 
 FROM COURSEENROLLMENTS;
 
 SELECT FIRSTNAME,REVERSE(FIRSTNAME) AS REVERSEDNAME,
 CHAR_LENGTH(FIRSTNAME) AS TOTALCHARACTERS
 FROM COURSEENROLLMENTS;
 
 SELECT FIRSTNAME,LOCATE('A',FIRSTNAME) AS LETTERPOSITION
FROM COURSEENROLLMENTS; 

SELECT FIRSTNAME,UPPER(REPLACE(FIRSTNAME,'a','o')) AS MODIFIEDNAME
FROM COURSEENROLLMENTS;

SELECT FIRSTNAME,LPAD(FIRSTNAME,12, '0') AS PADDEDNAME FROM COURSEENROLLMENTS;

SELECT CONCAT(RIGHT(COURSENAME,2), '-',LEFT(FIRSTNAME,2)) AS COURSELABEL FROM COURSEENROLLMENTS;

SELECT CONCAT(UPPER(SUBSTRING(FIRSTNAME,1,3)),LOWER(RIGHT(LASTNAME,2))) AS STUDENTNAME
FROM COURSEENROLLMENTS;

SELECT FEE,ROUND(FEE,1) AS ROUNDEDONEDECIMAL,
ROUND(FEE,0) AS ROUNDEDWHOLENUMBER
FROM COURSEENROLLMENTS;

SELECT FEE,CEIL(FEE)AS ROUNDEDUP,
FLOOR(FEE) AS ROUNDEDDOWN
FROM COURSEENROLLMENTS;

SELECT FEE,MOD(FEE,500) AS REMAINDER
FROM COURSEENROLLMENTS;

SELECT FEE,ABS(FEE-10000) AS DIFFERENCE FROM COURSEENROLLMENTS;

SELECT FEE,ROUND(FEE*1.18,2) AS TOTALFEE FROM COURSEENROLLMENTS;

SELECT FEE,FORMAT(FEE,2) AS FORMATTEDFEE FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,YEAR(ENROLLMENTDATE)AS ENROLLMENTYEAR,
MONTHNAME(ENROLLMENTDATE)AS MONTHNAME,
DAYNAME(ENROLLMENTDATE) AS DAYNAME
FROM COURSEENROLLMENTS;

SELECT DATE_FORMAT(ENROLLMENTDATE,'%D/%M/%Y') AS ENROLLMENT_DATE,
DATE_FORMAT(COMPLETIONDATE,'%M %D,%Y') AS COMPLETION_DATE
FROM COURSEENROLLMENTS;
 
SELECT ENROLLMENTDATE,COMPLETIONDATE,TIMESTAMPDIFF(DAY,ENROLLMENTDATE,COMPLETIONDATE)AS TOTALDAYS
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,DATE_ADD(DATE_ADD(ENROLLMENTDATE,INTERVAL 1 MONTH), 
INTERVAL 10 DAY) AS NEWDATE FROM COURSEENROLLMENTS;

SELECT COMPLETIONDATE,DATE_ADD(COMPLETIONDATE,INTERVAL -7 DAY) AS PREVIOUSDATE 
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,COMPLETIONDATE,TIMESTAMPDIFF(MONTH,ENROLLMENTDATE,COMPLETIONDATE)AS TOTALMONTHS 
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,DATE_ADD(DATE_ADD(DATE_ADD(ENROLLMENTDATE,INTERVAL 1 YEAR), INTERVAL 2 MONTH),INTERVAL 5 DAY) AS NEWDATE
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,DAYNAME(ENROLLMENTDATE) AS ENROLLMENTDATE,COMPLETIONDATE,
DAYNAME(COMPLETIONDATE) AS COMPLETIONDATE
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,CURDATE()AS TODAYDATE,TIMESTAMPDIFF(DAY, ENROLLMENTDATE,CURDATE())AS TOTALDAYS
FROM COURSEENROLLMENTS;

SELECT DATE_FORMAT(COMPLETIONDATE,'%D/%M/%Y') AS ORIGINALNAME,
DATE_FORMAT(DATE_ADD(COMPLETIONDATE,INTERVAL 15 DAY),'%D/%M/%Y') AS NEWDATE
FROM COURSEENROLLMENTS;







 

 
 
 
 
 